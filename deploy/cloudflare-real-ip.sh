#!/bin/sh
# Writes an nginx snippet telling it to trust Cloudflare's forwarded client
# address, so $remote_addr is the employee rather than a Cloudflare edge.
#
#   sudo deploy/cloudflare-real-ip.sh && sudo nginx -t && sudo systemctl reload nginx
#
# Why this matters here more than on a brochure site: this application stores
# the IP against every punch event, every sign-in attempt and every audit
# entry. Behind a proxy, without this, all of them record the proxy. The
# column still fills, which is what makes it dangerous — it looks like
# evidence and is not.
#
# Cloudflare publishes these ranges and they change occasionally. Re-run after
# a change; nothing here pins a date, so running it again is always safe.
#
# set_real_ip_from only grants trust to those ranges. A request arriving from
# anywhere else keeps its own address, so this cannot be used to spoof an
# address by setting the header yourself — provided the origin is not
# reachable directly, which is the other reason to keep it firewalled.
set -eu

OUT=/etc/nginx/conf.d/cloudflare-real-ip.conf
TMP=$(mktemp)

trap 'rm -f "$TMP"' EXIT

printf '# Generated by deploy/cloudflare-real-ip.sh — do not edit by hand.\n' > "$TMP"

for url in https://www.cloudflare.com/ips-v4 https://www.cloudflare.com/ips-v6; do
    curl -fsS --max-time 20 "$url" | while read -r cidr; do
        [ -n "$cidr" ] && printf 'set_real_ip_from %s;\n' "$cidr"
    done
done >> "$TMP"

# CF-Connecting-IP carries the original client and is set by Cloudflare on
# every request. Preferred over X-Forwarded-For, which can already hold a
# chain by the time it arrives.
printf 'real_ip_header CF-Connecting-IP;\n' >> "$TMP"

# Refuse to install an empty or truncated file: a half-written snippet would
# silently trust nothing and leave every address reading as Cloudflare again.
if [ "$(grep -c '^set_real_ip_from' "$TMP")" -lt 10 ]; then
    echo "Fetched too few ranges — refusing to install. Check network access." >&2
    exit 1
fi

install -m 0644 "$TMP" "$OUT"
echo "Wrote $OUT with $(grep -c '^set_real_ip_from' "$OUT") ranges."
echo "Uncomment the include in the vhost, then: nginx -t && systemctl reload nginx"
